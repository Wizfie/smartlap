async function seed() {
  console.log('--- Memulai Seeding Produk & Gambar Lokal SmartLap ---');

  for (const p of products) {
    const laptop = await prisma.laptop.upsert({
      where: { id: p.id },
      update: {
        brand: p.brand,
        model: p.model,
        sku: p.sku,
        price: p.price,
        stock: p.stock,
        processorName: p.processor_name,
        processorScore: p.processor_score,
        ramGb: p.ram_gb,
        storageDesc: p.storage_desc,
        storageGb: p.storage_gb,
        gpuName: p.gpu_name,
        gpuScore: p.gpu_score,
        batteryHours: p.battery_hours,
        weightKg: p.weight_kg,
        screenDesc: p.screen_desc,
        imageUrl: p.image_url,
        description: p.description
      },
      create: {
        id: p.id,
        brand: p.brand,
        model: p.model,
        sku: p.sku,
        price: p.price,
        stock: p.stock,
        processorName: p.processor_name,
        processorScore: p.processor_score,
        ramGb: p.ram_gb,
        storageDesc: p.storage_desc,
        storageGb: p.storage_gb,
        gpuName: p.gpu_name,
        gpuScore: p.gpu_score,
        batteryHours: p.battery_hours,
        weightKg: p.weight_kg,
        screenDesc: p.screen_desc,
        imageUrl: p.image_url,
        description: p.description
      }
    });

    // Sinkronisasi nilai kriteria matriks SAW (C1 s/d C6)
    const criteriaMappings = [
      { criterionId: 1, rawValue: p.price },           // C1: Harga (Cost)
      { criterionId: 2, rawValue: p.processor_score }, // C2: CPU (Benefit)
      { criterionId: 3, rawValue: p.ram_gb },          // C3: RAM (Benefit)
      { criterionId: 4, rawValue: p.gpu_score },       // C4: GPU (Benefit)
      { criterionId: 5, rawValue: p.storage_gb },      // C5: Storage (Benefit)
      { criterionId: 6, rawValue: p.battery_hours }    // C6: Baterai (Benefit)
    ];

    for (const c of criteriaMappings) {
      await prisma.laptopCriteriaValue.upsert({
        where: {
          laptopId_criterionId: {
            laptopId: laptop.id,
            criterionId: c.criterionId
          }
        },
        update: { rawValue: c.rawValue },
        create: {
          laptopId: laptop.id,
          criterionId: c.criterionId,
          rawValue: c.rawValue
        }
      });
    }

    console.log(`✓ [${p.id}] ${p.brand} ${p.model} -> ${p.image_url}`);
  }

  console.log(`\nBerhasil memperbarui & menambah ${products.length} laptop ke database beserta gambar lokal!`);
  await prisma.$disconnect();
}

seed().catch((e) => {
  console.error('Error saat seeding:', e);
  process.exit(1);
});
